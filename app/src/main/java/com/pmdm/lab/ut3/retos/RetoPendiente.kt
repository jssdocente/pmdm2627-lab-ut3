// Pantalla provisional de un reto: sustitúyela por tu solución
@Composable
fun RetoPendiente(titulo: String, modifier: Modifier = Modifier) {
    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(24.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(8.dp, Alignment.CenterVertically)
    ) {
        Text(text = titulo, style = MaterialTheme.typography.headlineSmall)
        Text(
            text = "Reto pendiente: lee los TODO de su archivo y el enunciado en los apuntes (3.6).",
            style = MaterialTheme.typography.bodyMedium,
            textAlign = TextAlign.Center,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )
    }
}
